#!/usr/bin/env python3
"""
settlement_months_benchmark.py — is the $764.7B cap-relative benchmark an
artifact of the CALENDAR-month netting convention?

PRE-COMMITTED SPEC (fixed in this header BEFORE any run).

HANDOFF_round22.md §6.3 (round-21 R10 leftover, never started). Liveness gate #96.

WHY THIS MATTERS MORE THAN ITS SIZE SUGGESTS
--------------------------------------------
$764.7482532227002B is the DENOMINATOR of every percentage in the paper — every
recovery level, the beta_1 = 0 null at 85.7%, the marginal at +5.6 points, the
hull, the Danish gap. R10 listed "settlement-months benchmark variant" as a
one-line leftover and never defined it. A referee asking "does your denominator
depend on the month-alignment convention?" currently has no answer at all. This
run gives one.

THE TWO CONVENTIONS
-------------------
The benchmark nets realized SOMA roll-off against the phased cap schedule month
by month (macro.build_empirical_metrics:229-235; cap schedule
common/qt_window.py:60-74: -$17.5B/mo Jun-Aug 2022, -$35B/mo Sep 2022-Nov 2025,
42 active months, $1,417.5B total).

  CALENDAR (production). Net cash arriving in month t against the cap for
  month t. This is what the cap literally constrains: the FOMC set a ceiling on
  principal NOT reinvested in a given month, and that is a statement about cash.

  SETTLEMENT-ALIGNED (this variant). Agency remittance means the cash arriving
  in month t was generated by prepayment decisions in months t, t-1, t-2. The
  repo already carries the mapping, committed and untuned:
    abm/fed_mbs_extension_risk.py:91
      SETTLEMENT_LAG_KERNEL = [0.10, 0.60, 0.30]   # lags 0/1/2, mass-conserving
      "Sourced from standard 55-day / ~50-day agency remittance cycles, not tuned."
  and the manuscript already asserts the mechanism (V.B: loan-level prepayment
  decisions show up in SOMA cash two to three months later). So the variant
  introduces NO new parameter. It reuses the committed kernel.

IMPLEMENTATION — CONVOLVE THE CAP, DO NOT DECONVOLVE THE CASH
-------------------------------------------------------------
The realized series is the noisy observable; deconvolution against a 3-tap
kernel is ill-conditioned and would manufacture structure. The cap schedule is a
deterministic step function known exactly. So the variant convolves the CAP
forward with the same kernel —
    cap_settle[t] = 0.10*cap[t] + 0.60*cap[t-1] + 0.30*cap[t-2]
with pre-QT months contributing 0 (there was no cap before QT_START) — and nets
the unchanged realized series against it. This is the numerically stable
direction and it is exactly equivalent to asking: "given when cash actually
arrives, what cap does the schedule imply for each arrival month?"

MASS IS NOT CONSERVED INSIDE THE WINDOW, AND THAT IS THE POINT. The kernel is
mass-conserving on an infinite line, but the window is half-open, so cap mass
convolved past QT_END is dropped. The loss is at the window's END, not its start:

  Oct 2025 cap: the lag-2 tap lands in Dec 2025, outside -> 0.30 x $35B = $10.5B
  Nov 2025 cap: the lag-1 and lag-2 taps land in Dec 2025 / Jan 2026, outside
                                                  -> 0.90 x $35B = $31.5B
  total leaving the window                                       -> $42.0B

The window's START loses nothing FROM THE SCHEDULE — the pre-QT cap is zero, so
there is no mass to draw in; the ramp is merely redistributed within the window.
The settlement-aligned cap total is therefore mechanically smaller than $1,417.5B
by $42.0B, and because the realized series is untouched and both legs sum over
the same months, the benchmark shifts by EXACTLY that amount. The run reports the
decomposition so the shift cannot be read as behavioural.

(An earlier draft of this header attributed the loss to the window's first two
months and put it near $21B. That was wrong on both the edge and the magnitude;
the code was always correct and the run's own numbers exposed it. Recorded rather
than quietly corrected, per the project's standing rule about checks that
disagree with artifacts.)

SPEC (fixed ex ante)
- One macro frame, fetched once (macro.fetch_data + fetch_soma_mbs_monthly),
  scored through macro.build_empirical_metrics unchanged for the calendar leg.
- The settlement leg re-derives Extension_Delta and the cumulative trapped total
  with cap_settle in place of QT_Target_Billions, over the identical
  qt_active_mask window. Nothing else changes: same realized series, same
  window, same sign convention.
- Sensitivity legs: the same computation under kernels [1,0,0] (degenerate =
  calendar; a wiring check that must reproduce the calendar leg BIT-EXACTLY),
  and under two disclosed alternates that bracket the remittance cycle,
  [0.0,0.5,0.5] (slower) and [0.3,0.6,0.1] (faster). These bound the convention,
  they are NOT competing estimates, and none is offered as production.
- NO microsim runs. This is pure accounting on the macro frame; runtime is the
  FRED/SOMA fetch plus arithmetic.

PARITY GATES (block interpretation; tol 1e-9)
  G0 the calendar leg reproduces the committed benchmark 764.7482532227002
     exactly. A FAIL means FRED/SOMA revised upstream and the run HALTS —
     the round-22 C1 rule: the tolerance is not widened to accommodate drift.
  G1 the cap schedule totals $1,417.5B over 42 active months (3 x 17.5 +
     39 x 35), asserted from common/qt_window.py rather than hard-coded alone.
  G2 the degenerate kernel [1,0,0] reproduces the calendar leg bit-exactly.
     This is the wiring check: if it fails, the convolution path is wrong and
     every other number here is meaningless.
  G3 the production kernel sums to 1.0 to 1e-12 and is read from
     abm.fed_mbs_extension_risk.SETTLEMENT_LAG_KERNEL, never retyped.

EX-ANTE INTERPRETIVE PARTITION (fixed before any result is seen)
  The PRODUCTION CONVENTION STAYS CALENDAR under every branch. That is
  pre-committed here so the result cannot be used to swap conventions after the
  fact: the cap is the only policy-committed quantity in this paper (V.B's
  standing reason for keeping the cap as headline at all), and it is committed
  in cash-arrival months. The variant is a robustness check on the denominator,
  never a competing headline.
  T1  |benchmark shift| <= 2% of the committed benchmark. The convention is
      immaterial; report one sentence in the benchmark subsection and a row in
      the run ledger. No percentage in the paper moves.
  T2  2% < |shift| <= 10%. Report the shifted benchmark AND the re-based
      headline percentages (null, marginal, Path B level) as a disclosed
      sensitivity in VII, with the mechanical window-edge decomposition stated
      so the shift is not read as behavioural.
  T3  |shift| > 10%. The convention is material to the headline: it must reach
      the abstract's benchmark sentence, and the limitations section must say
      the denominator is convention-dependent at that magnitude.
  T4  (DEGENERATE) any parity gate fails. Nothing interpretive is reported.

WHAT THIS DOES NOT SETTLE, stated ex ante: it tests month-ALIGNMENT only. It
does not revisit the cap schedule itself, the SOMA series, the window bounds, or
the reinvestment-ceiling reading of the cap. A T1 licenses "the benchmark is
insensitive to the netting convention", never "the benchmark is correct".

Run:  cd hazard && python3 settlement_months_benchmark.py
Runtime: ~20 s, dominated by the FRED/SOMA fetch.
"""
from __future__ import annotations

import json
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "abm"))

from macro import build_empirical_metrics, fetch_data, fetch_soma_mbs_monthly
from common.qt_window import (  # noqa: E402
    QT_END, QT_RAMP_END, QT_START, QT_TARGET_FULL_B, QT_TARGET_RAMP_B,
    compute_qt_target_series, qt_active_mask,
)

DATA_DIR = Path(__file__).parent / "data"
RESULTS_JSON = DATA_DIR / "settlement_months_benchmark_results.json"

COMMITTED_BENCHMARK_B = 764.7482532227002
COMMITTED_CAP_TOTAL_B = 1417.5
TOL = 1e-9

GATES: dict = {}


def _gate(name, got, want, tol=TOL, note=""):
    diff = abs(got - want)
    GATES[name] = {"got": got, "want": want, "diff": diff, "tol": tol,
                   "bit_exact": diff == 0.0, "pass": bool(diff < tol),
                   "note": note}
    print(f"gate {name}: got {got:.10f} want {want:.10f} diff {diff:.3e} "
          f"[{'PASS' if diff < tol else 'FAIL'}"
          f"{', bit-exact' if diff == 0.0 else ''}] {note}")


def _halt(reason: str):
    RESULTS_JSON.write_text(json.dumps(
        {"mode": "settlement_months_benchmark", "status": "GATE_FAILURE",
         "reason": reason, "gates": GATES, "interpretive_verdict": "T4",
         "generated_utc": datetime.now(timezone.utc).isoformat()}, indent=1))
    raise SystemExit(f"[T4 / GATE FAILURE] {reason}")


def convolve_cap(cap: pd.Series, kernel) -> pd.Series:
    """cap_settle[t] = sum_l kernel[l] * cap[t-l]; pre-QT months contribute 0."""
    base = cap.fillna(0.0)
    out = pd.Series(0.0, index=cap.index)
    for lag, w in enumerate(kernel):
        out = out + w * base.shift(lag, fill_value=0.0)
    return out


def trapped_total(df: pd.DataFrame, cap: pd.Series) -> float:
    """Cumulative shortfall of realized roll-off against `cap`, QT window only."""
    mask = qt_active_mask(df.index)
    delta = (df["Actual_Monthly_Rolloff_Billions"] - cap).where(mask)
    return float(delta.fillna(0.0).where(mask, 0.0).sum())


def main() -> None:
    t0 = time.perf_counter()
    DATA_DIR.mkdir(parents=True, exist_ok=True)

    from fed_mbs_extension_risk import SETTLEMENT_LAG_KERNEL
    kernel = list(SETTLEMENT_LAG_KERNEL)
    _gate("G3_kernel_sums_to_one", float(sum(kernel)), 1.0, 1e-12,
          f"kernel={kernel} read from fed_mbs_extension_risk")

    macro = fetch_data()
    soma = fetch_soma_mbs_monthly()
    df = build_empirical_metrics(macro, soma_rolloff=soma)

    cap_cal = compute_qt_target_series(df.index)
    mask = qt_active_mask(df.index)
    n_active = int(mask.sum())
    cap_total = float(cap_cal.where(mask).fillna(0.0).sum())
    _gate("G1_cap_schedule_total", abs(cap_total), COMMITTED_CAP_TOTAL_B, 1e-6,
          f"{n_active} active months, ramp {QT_TARGET_RAMP_B} full {QT_TARGET_FULL_B}")

    bench_cal = trapped_total(df, cap_cal)
    _gate("G0_calendar_reproduces_committed", bench_cal, COMMITTED_BENCHMARK_B,
          1e-9, "FRED/SOMA drift halts the run; tolerance is NOT widened")

    bench_degen = trapped_total(df, convolve_cap(cap_cal, [1.0, 0.0, 0.0]))
    _gate("G2_degenerate_kernel_is_calendar", bench_degen, bench_cal, 1e-9,
          "wiring check on the convolution path")

    if not all(g["pass"] for g in GATES.values()):
        _halt("failed: " + ", ".join(k for k, g in GATES.items() if not g["pass"]))

    legs = {}
    for tag, k in (("production", kernel), ("slower", [0.0, 0.5, 0.5]),
                   ("faster", [0.3, 0.6, 0.1])):
        cap_s = convolve_cap(cap_cal, k)
        b = trapped_total(df, cap_s)
        cap_s_total = float(cap_s.where(mask).fillna(0.0).sum())
        legs[tag] = {
            "kernel": list(k),
            "benchmark_b": b,
            "shift_b": b - bench_cal,
            "shift_pct_of_committed": (b - bench_cal) / COMMITTED_BENCHMARK_B * 100.0,
            "cap_total_b": abs(cap_s_total),
            "cap_mass_lost_b": COMMITTED_CAP_TOTAL_B - abs(cap_s_total),
        }
        print(f"  {tag:11s} kernel={k}  benchmark ${b:.4f}B  "
              f"shift {b - bench_cal:+.4f}B  cap total ${abs(cap_s_total):.2f}B")

    prod = legs["production"]
    shift_pct = abs(prod["shift_pct_of_committed"])
    if shift_pct <= 2.0:
        verdict, label = "T1", "convention immaterial"
    elif shift_pct <= 10.0:
        verdict, label = "T2", "disclosed sensitivity, headline unchanged"
    else:
        verdict, label = "T3", "convention material to the headline"

    # Window-edge decomposition: how much of the shift is mechanical?
    edge_lost = COMMITTED_CAP_TOTAL_B - prod["cap_total_b"]
    payload = {
        "mode": "settlement_months_benchmark",
        "pre_committed": True,
        "spec": ("convolve the cap schedule with the committed settlement-lag "
                 "kernel; net the unchanged realized series against it; "
                 "calendar convention stays production under every branch"),
        "production_convention_stays_calendar": True,
        "committed_benchmark_b": COMMITTED_BENCHMARK_B,
        "calendar_benchmark_b": bench_cal,
        "kernel_production": kernel,
        "legs": legs,
        "n_qt_active_months": n_active,
        "cap_total_calendar_b": abs(cap_total),
        "window_edge_cap_mass_lost_b": edge_lost,
        "shift_explained_by_window_edge": (
            "The settlement-aligned cap loses mass at the window's END, not its "
            "start: the half-open window drops cap convolved past QT_END "
            "(Oct 2025 loses its lag-2 tap, 0.30 x $35B; Nov 2025 loses lags 1 "
            "and 2, 0.90 x $35B; $42.0B in total). The window's start loses "
            "nothing from the schedule because the pre-QT cap is zero — the ramp "
            "is only redistributed within the window. The loss is mechanical, "
            "not behavioural, and because the realized series is untouched and "
            "both legs sum over the same months it accounts for "
            f"${edge_lost:.3f}B of the ${abs(prod['shift_b']):.3f}B shift "
            "exactly."),
        "shift_pct_abs": shift_pct,
        "interpretive_verdict": f"{verdict}: {label} — settlement-aligned "
                                f"benchmark ${prod['benchmark_b']:.4f}B against the "
                                f"calendar ${bench_cal:.4f}B, a shift of "
                                f"{prod['shift_pct_of_committed']:+.3f}% of the "
                                f"committed benchmark.",
        "t1_immaterial": verdict == "T1",
        "t2_disclosed_sensitivity": verdict == "T2",
        "t3_material_to_headline": verdict == "T3",
        "residual_scope_not_settled": (
            "Tests month-ALIGNMENT only. Does not revisit the cap schedule, the "
            "SOMA series, the window bounds, or the reinvestment-ceiling reading "
            "of the cap."),
        "gates": GATES,
        "gates_all_pass": True,
        "runtime_s": time.perf_counter() - t0,
        "generated_utc": datetime.now(timezone.utc).isoformat(),
    }
    RESULTS_JSON.write_text(json.dumps(payload, indent=1))
    print(f"\n{payload['interpretive_verdict']}")
    print(f"window-edge mass lost: ${edge_lost:.3f}B of the "
          f"${abs(prod['shift_b']):.3f}B shift")
    print(f"wrote {RESULTS_JSON}  ({payload['runtime_s']:.1f}s)")


if __name__ == "__main__":
    main()
